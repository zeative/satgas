export type Lang = "en" | "id";
const LANG_KEY = "satgas.lang";
// English for everyone until the person picks another language; the browser's language never switches it on its own.
const stored = (() => {
  try {
    return localStorage.getItem(LANG_KEY);
  } catch {
    return null;
  }
})();
export const lang: Lang = stored === "id" ? "id" : "en";
export const t = lang === "id" ? id : en;
// Each language by its own name, so people find theirs whatever language the page is in now.
export const LANGS: [Lang, string][] = [
  ["en", "English"],
  ["id", "Bahasa Indonesia"],
];

// Every string is picked once at load, so a new language takes effect with a reload.
export function setLang(next: Lang) {
  if (next === lang) return;
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    return;
  }
  location.reload();
}

document.documentElement.lang = lang;

export const isMac = /mac|iphone|ipad/i.test(navigator.platform || navigator.userAgent);

export function fmtElapsed(ms: number): string {
  const s = Math.max(0, Math.floor(ms / 1000));
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}m ${String(s % 60).padStart(2, "0")}s`;
  return `${Math.floor(m / 60)}h ${String(m % 60).padStart(2, "0")}m`;
}

const rtf = new Intl.RelativeTimeFormat(lang, { numeric: "auto", style: "short" });

const compact = new Intl.NumberFormat(lang, { notation: "compact", maximumFractionDigits: 1 });
export const fmtCompact = (n: number) => compact.format(n);

export function fmtAgo(ts: number, now = Date.now()): string {
  // Callers tick slowly, so a fresh timestamp can sit ahead of `now`; it still happened, never "in 4 sec".
  const s = Math.min(0, Math.round((ts - now) / 1000));
  if (s > -60) return rtf.format(s, "second");
  const m = Math.round(s / 60);
  if (m > -60) return rtf.format(m, "minute");
  const h = Math.round(m / 60);
  if (h > -24) return rtf.format(h, "hour");
  return rtf.format(Math.round(h / 24), "day");
}

