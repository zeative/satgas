// Vendors a skills repo into Satgas as built-in skills, written out fresh at every start.
// Usage: bun scripts/vendor-skills.ts <path to a clone> [name, default agent-skills]
//   agent-skills:   a clone of github.com/addyosmani/agent-skills
//   security-audit: a clone of github.com/cloudflare/security-audit-skill
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, posix, relative } from "node:path";

const repo = process.argv[2];
const pack = process.argv[3] ?? "agent-skills";
if (!repo) throw new Error("Pass the path to a clone of the skills repo.");
if (!/^[a-z0-9-]+$/.test(pack)) throw new Error("The name is lowercase words joined by dashes.");
// AGENT_SKILLS, SECURITY_AUDIT: what the generated module exports.
const NAME = pack.toUpperCase().replace(/-/g, "_");

const ROOT = join(import.meta.dir, "..");
const OUT = join(ROOT, `src/server/builtin-skills/${pack}`);
const GEN = join(ROOT, `src/server/builtin-skills/${pack}.gen.ts`);
// A link out of a skill to the repo's shared references folder.
const SHARED = /(?:\.\.\/){2,}references\/([a-z0-9-]+\.md)/g;

const commit = (await Bun.$`git -C ${repo} rev-parse HEAD`.text()).trim();
const origin = (await Bun.$`git -C ${repo} remote get-url origin`.text())
  .trim()
  .replace(/^https:\/\/|^git@/, "")
  .replace(":", "/")
  .replace(/\.git$/, "");

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

// Built-in skills are embedded as text; pictures (a theme's preview shots) stay in the repo instead of in Satgas.
const BINARY = /\.(jpe?g|png|gif|webp|avif|ico|pdf|woff2?|ttf|otf|zip|gz)$/i;
let skipped = 0;

// Non-markdown files sit in the source tree as .txt, so the build embeds them as text and lint leaves them alone.
const stored = (rel: string) => (rel.endsWith(".md") ? rel : `${rel}.txt`);

await rm(OUT, { recursive: true, force: true });
const skills: Record<string, string[]> = {};
for (const name of (await readdir(join(repo, "skills"))).sort()) {
  const dir = join(repo, "skills", name);
  const all = (await walk(dir)).map((f) => relative(dir, f).split("\\").join("/")).sort();
  const files = all.filter((f) => !BINARY.test(f));
  skipped += all.length - files.length;
  if (!files.includes("SKILL.md")) continue;
  const shared = new Set<string>();
  const write = async (rel: string, text: string) => {
    await mkdir(dirname(join(OUT, name, stored(rel))), { recursive: true });
    await writeFile(join(OUT, name, stored(rel)), text);
  };
  for (const rel of files) {
    let text = await readFile(join(dir, rel), "utf8");
    // Installed skills live apart from the repo's references folder, so each skill carries the ones it links to.
    text = text.replace(SHARED, (_, file: string) => {
      shared.add(file);
      return posix.relative(posix.dirname(rel), `shared/${file}`);
    });
    await write(rel, text);
  }
  for (const file of shared) {
    const text = (await readFile(join(repo, "references", file), "utf8")).replace(SHARED, "$1");
    await write(`shared/${file}`, text);
  }
  skills[name] = [...files, ...[...shared].map((f) => `shared/${f}`)];
}
await writeFile(join(OUT, "LICENSE"), await readFile(join(repo, "LICENSE"), "utf8"));

const lines = [`// Generated by scripts/vendor-skills.ts from ${origin} at ${commit}. Do not edit.`];
const map: string[] = [];
let n = 0;
for (const [name, files] of Object.entries(skills)) {
  const entries: string[] = [];
  for (const rel of files) {
    const id = `f${n++}`;
    lines.push(`import ${id} from "./${pack}/${name}/${stored(rel)}" with { type: "text" };`);
    entries.push(`    ${JSON.stringify(rel)}: ${id},`);
  }
  map.push(`  ${JSON.stringify(name)}: {\n${entries.join("\n")}\n  },`);
}
lines.push(
  "",
  `export const ${NAME}_COMMIT = ${JSON.stringify(commit)};`,
  "",
  `export const ${NAME}: Record<string, Record<string, string>> = {`,
  ...map,
  "};",
  "",
);
await writeFile(GEN, lines.join("\n"));
console.log(
  `Vendored ${Object.keys(skills).length} skills from ${commit.slice(0, 7)}${skipped ? `, leaving out ${skipped} pictures` : ""}.`,
);
