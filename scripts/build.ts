// Builds the single-file release: Vite builds the UI, then the server is compiled with every UI file embedded.
import { readdir, rm } from "node:fs/promises";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const webDir = join(root, "dist/web");
const manifest = join(root, "src/server/assets.gen.ts");

function run(cmd: string[], env: Record<string, string> = {}) {
  const proc = Bun.spawnSync(cmd, { cwd: root, stdout: "inherit", stderr: "inherit", env: { ...process.env, ...env } });
  if (proc.exitCode !== 0) throw new Error(`${cmd.join(" ")} failed with exit code ${proc.exitCode}`);
}

async function files(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true, recursive: true });
  return entries.filter((e) => e.isFile()).map((e) => join(e.parentPath, e.name));
}

run(["bunx", "vite", "build"]);

const paths = await files(webDir);
const imports = paths.map((p, i) => `import f${i} from ${JSON.stringify(relative(join(root, "src/server"), p))} with { type: "file" };`);
const entries = paths.map((p, i) => `  ${JSON.stringify(`/${relative(webDir, p)}`)}: f${i},`);
await Bun.write(
  manifest,
  `// Generated by scripts/build.ts while compiling the binary. Do not edit.\n${imports.join("\n")}\n\nexport const assets: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);

// `bun scripts/build.ts linux-x64 darwin-arm64` builds release files; with no target, one binary for this machine.
const targets = process.argv.slice(2);
const compile = (outfile: string, target?: string) =>
  // Baked in, so the binary never serves Bun's development error pages (they show source) on a server.
  run(
    [
      "bun",
      "build",
      "--compile",
      "--minify",
      "--define",
      'process.env.NODE_ENV="production"',
      ...(target ? [`--target=bun-${target}`] : []),
      "src/server/main.ts",
      "--outfile",
      outfile,
    ],
    { NODE_ENV: "production" },
  );

try {
  if (targets.length) for (const target of targets) compile(`dist/release/satgas-${target}`, target);
  else compile("dist/satgas");
} finally {
  await rm(manifest, { force: true });
}
console.log(`\nBuilt ${targets.length ? `dist/release (${targets.join(", ")})` : "dist/satgas"} with ${paths.length} embedded UI files.`);
